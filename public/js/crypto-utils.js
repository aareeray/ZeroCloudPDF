// 1. FILE HASH CHECKER
export async function calculateFileHashes(file, options, onProgress) {
  if (onProgress) onProgress('Reading file bytes into memory...');
  const buffer = await file.arrayBuffer();

  if (onProgress) onProgress('Calculating SHA-256...');
  const sha256Buf = await crypto.subtle.digest('SHA-256', buffer);
  const sha256 = bufToHex(sha256Buf);

  if (onProgress) onProgress('Calculating SHA-512...');
  const sha512Buf = await crypto.subtle.digest('SHA-512', buffer);
  const sha512 = bufToHex(sha512Buf);

  if (onProgress) onProgress('Calculating SHA-1...');
  const sha1Buf = await crypto.subtle.digest('SHA-1', buffer);
  const sha1 = bufToHex(sha1Buf);

  if (onProgress) onProgress('Calculating MD5...');
  // Read first 1MB as binary string for fast MD5 check
  const sliceLen = Math.min(buffer.byteLength, 1024 * 1024 * 2);
  const uint8 = new Uint8Array(buffer.slice(0, sliceLen));
  let binaryStr = '';
  for (let i = 0; i < uint8.length; i++) {
    binaryStr += String.fromCharCode(uint8[i]);
  }
  const md5Hash = md5(binaryStr);

  const report = {
    fileName: file.name,
    fileSize: `${(file.size / 1024).toFixed(2)} KB (${file.size.toLocaleString()} bytes)`,
    'SHA-256': sha256,
    'SHA-512': sha512,
    'SHA-1': sha1,
    'MD5': md5Hash
  };

  const expected = (options.verifyHash || '').trim().toLowerCase();
  let verification = null;
  if (expected) {
    if (sha256 === expected || sha512 === expected || sha1 === expected || md5Hash === expected) {
      verification = { match: true, message: '✅ Checksum matches perfectly! The file is authentic and unaltered.' };
    } else {
      verification = { match: false, message: '❌ Checksum mismatch! The file hash does not match the expected value.' };
    }
  }

  return {
    report,
    verification,
    reportText: `File: ${file.name}\nSize: ${file.size} bytes\n\nSHA-256:\n${sha256}\n\nSHA-512:\n${sha512}\n\nSHA-1:\n${sha1}\n\nMD5:\n${md5Hash}\n`
  };
}

// 2. PASSWORD GENERATOR
export function generateSecurePassword(options) {
  const length = parseInt(options.length, 10) || 16;
  let charset = '';

  const uppercase = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  const lowercase = 'abcdefghijklmnopqrstuvwxyz';
  const numbers = '0123456789';
  const symbols = '!@#$%^&*()-_=+[]{}|;:,.<>?';

  if (options.includeUpper !== false) charset += uppercase;
  if (options.includeLower !== false) charset += lowercase;
  if (options.includeNumbers !== false) charset += numbers;
  if (options.includeSymbols !== false) charset += symbols;

  if (!charset) charset = lowercase + numbers;

  const randomValues = new Uint32Array(length);
  crypto.getRandomValues(randomValues);

  let password = '';
  for (let i = 0; i < length; i++) {
    password += charset[randomValues[i] % charset.length];
  }

  // Calculate Shannon entropy bits
  const entropy = Math.round(length * Math.log2(charset.length));
  let strength = 'Moderate';
  let color = '#f59e0b';
  if (entropy >= 80) {
    strength = 'Military-Grade';
    color = '#10b981';
  } else if (entropy >= 60) {
    strength = 'Very Strong';
    color = '#06b6d4';
  } else if (entropy >= 45) {
    strength = 'Strong';
    color = '#3b82f6';
  } else {
    strength = 'Weak';
    color = '#ef4444';
  }

  return {
    password,
    entropy: `${entropy} bits of entropy`,
    strength,
    color
  };
}
